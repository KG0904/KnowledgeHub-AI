import uuid
from qdrant_client import QdrantClient
from qdrant_client.models import Distance, VectorParams, PointStruct


# Connect to the Qdrant server running in Docker.
# "qdrant" is the service name from docker-compose.yml.
client = QdrantClient(
    host="qdrant",
    port=6333,
)


# Name of the collection where document chunks will be stored.
COLLECTION_NAME = "document_embeddings"


def create_collection():

    # Check whether the collection already exists.
    # If it exists, we don't create it again.
    if not client.collection_exists(COLLECTION_NAME):

        # Create a new collection for storing document embeddings.
        client.create_collection(
            collection_name=COLLECTION_NAME,

            # Each embedding generated by all-MiniLM-L6-v2
            # contains 384 numbers.
            vectors_config=VectorParams(
                size=384,

                # We will use cosine similarity to compare embeddings.
                distance=Distance.COSINE,
            ),
        )


def store_embeddings(document_id, chunks, embeddings):

    # Make sure the collection exists before inserting data.
    create_collection()

    points = []

    # Each chunk has a corresponding embedding.
    for chunk, embedding in zip(chunks, embeddings):

        #Create unique id for every chunk belonging to the document
        unique_id = str(uuid.uuid4())

        # Create one Qdrant point for this chunk.
        points.append(
            PointStruct(

                # Generate a unique ID for this Qdrant point.
                id=unique_id,

                # Store the embedding as the vector.
                vector=embedding,

                # Store additional information along with the vector.
                payload={
                    "document_id": document_id,
                    "text": chunk,
                },
            )
        )

    # Insert all points into the Qdrant collection.
    client.upsert(
        collection_name=COLLECTION_NAME,
        points=points,
    )

    print("All points inserted into Qdrant")
